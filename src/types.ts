//  В TypeScript-проекте удобно начинать именно отсюда: сначала описываем,
//  КАКИЕ данные у нас есть, а потом строим вокруг них интерфейс.
//  Эти типы я задал за тебя как пример — дальше ты будешь их использовать.

// Union type — «или то, или то». Значение может быть только одной из этих строк.
// TypeScript не даст присвоить сюда, например, 'salary' — будет ошибка.
export type TransactionType = 'income' | 'expense'

// Interface — описание формы объекта. Одна операция (доход или расход).
export interface Transaction {
  id: string
  title: string
  amount: number // всегда положительное число; знак задаёт поле type
  type: TransactionType
  createdAt: string // ISO-дата, напр. new Date().toISOString()
}
